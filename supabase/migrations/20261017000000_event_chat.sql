create table if not exists public.event_chat_messages (
  id bigint generated by default as identity primary key,
  event_id bigint not null,
  sender_user_id uuid,
  guest_id uuid,
  sender_name text not null,
  message text not null check (char_length(message) between 1 and 500),
  created_at timestamptz not null default now(),
  constraint event_chat_sender_check check (
    (sender_user_id is not null and guest_id is null) or
    (sender_user_id is null and guest_id is not null)
  )
);

create index if not exists event_chat_messages_event_created_idx
  on public.event_chat_messages (event_id, created_at);

alter table public.event_chat_messages enable row level security;

drop policy if exists "Anyone can read event chat" on public.event_chat_messages;
create policy "Anyone can read event chat"
  on public.event_chat_messages for select
  to anon, authenticated
  using (true);

revoke insert, update, delete on public.event_chat_messages from anon, authenticated;
grant select on public.event_chat_messages to anon, authenticated;

drop function if exists public.send_event_chat_message(bigint, text, uuid);

create or replace function public.send_event_chat_message(
  p_event_id bigint,
  p_message text,
  p_guest_id uuid default null,
  p_sender_name text default null
)
returns public.event_chat_messages
language plpgsql
security definer
set search_path = ''
as $$
declare
  current_user_id uuid := auth.uid();
  current_guest_id uuid;
  current_sender_name text;
  clean_message text := btrim(coalesce(p_message, ''));
  inserted_message public.event_chat_messages;
begin
  if p_event_id is null or p_event_id <= 0 then
    raise exception 'Event tidak valid.';
  end if;
  if char_length(clean_message) not between 1 and 500 then
    raise exception 'Pesan harus berisi 1 sampai 500 karakter.';
  end if;

  if current_user_id is null then
    if p_guest_id is null or char_length(btrim(coalesce(p_sender_name, ''))) not between 1 and 60 then
      raise exception 'Identitas pengunjung tidak valid.';
    end if;
    current_guest_id := p_guest_id;
    current_sender_name := btrim(p_sender_name);
  else
    current_guest_id := null;
    current_sender_name := coalesce(
      nullif(btrim(auth.jwt() -> 'user_metadata' ->> 'full_name'), ''),
      nullif(btrim(auth.jwt() ->> 'email'), ''),
      'Pengguna'
    );
  end if;

  if exists (
    select 1
    from public.event_chat_messages existing
    where existing.event_id = p_event_id
      and existing.created_at > now() - interval '2 seconds'
      and (
        (current_user_id is not null and existing.sender_user_id = current_user_id)
        or (current_user_id is null and existing.guest_id = current_guest_id)
      )
  ) then
    raise exception 'Tunggu sebentar sebelum mengirim pesan berikutnya.';
  end if;

  insert into public.event_chat_messages (
    event_id, sender_user_id, guest_id, sender_name, message
  ) values (
    p_event_id, current_user_id, current_guest_id, current_sender_name, clean_message
  )
  returning * into inserted_message;

  return inserted_message;
end;
$$;

revoke all on function public.send_event_chat_message(bigint, text, uuid, text) from public;
grant execute on function public.send_event_chat_message(bigint, text, uuid, text) to anon, authenticated;

do $$
begin
  if not exists (
    select 1
    from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'event_chat_messages'
  ) then
    alter publication supabase_realtime add table public.event_chat_messages;
  end if;
end;
$$;
